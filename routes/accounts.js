'use strict';
const express=require('express');
const controller=require('../controllers/accountController');
const sameOrigin=require('../middleware/writeOrigin');
const onlyGuest=require('../middleware/requireGuest');
const onlyCustomer=require('../middleware/requireCustomer');
const limitRequests=require('../middleware/limitRequests');
const validate=require('../middleware/validate');
const rules=require('../validations/userValidations');
const router=express.Router();
const wrap=require('../middleware/asyncHandler');
const loginLimit=limitRequests({max:12,windowMs:15*60*1000,namespace:'login'});
const registerLimit=limitRequests({max:5,windowMs:60*60*1000,namespace:'register'});
// Sprint 7: cada formulario pasa por express-validator antes de llegar al controlador.
router.post('/register',registerLimit,onlyGuest,sameOrigin,validate(rules.register),wrap(controller.register));
router.post('/login',loginLimit,onlyGuest,sameOrigin,validate(rules.login),wrap(controller.login));
router.post('/logout',onlyCustomer,sameOrigin,wrap(controller.logout));
router.get('/me',wrap(controller.sessionInfo));
router.get('/profile',onlyCustomer,wrap(controller.profile));
router.put('/profile',onlyCustomer,sameOrigin,validate(rules.profile),wrap(controller.updateProfile));
router.put('/password',onlyCustomer,sameOrigin,validate(rules.password),wrap(controller.updatePassword));
module.exports=router;
